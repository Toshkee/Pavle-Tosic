/* Writes src/lib/icons.generated.ts: the Lucide glyphs the site's tiles and
   cards use (from the site's react-icons) and the brand marks of its skills
   card (from the site's src/app/site/icons.ts), as plain SVG markup, so the
   film draws the same icons the site does. Run: npm run icons */
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";

const site = new URL("../../", import.meta.url).pathname;
const require = createRequire(site + "package.json");
const { createElement } = require("react");
const { renderToStaticMarkup } = require("react-dom/server");
const lu = require("react-icons/lu");

const LU = [
  "LuLaugh", "LuBriefcaseBusiness", "LuLayers", "LuRoute", "LuPartyPopper",
  "LuUserRoundSearch", "LuClipboardCheck", "LuGamepad2", "LuArrowRight",
  "LuArrowUp", "LuFileText", "LuCheck", "LuMinus", "LuX", "LuSun", "LuMoon",
  "LuPaperclip", "LuChevronLeft", "LuChevronRight",
];
const glyphs = {};
for (const name of LU) {
  if (!lu[name]) throw new Error(`no ${name} in react-icons/lu`);
  const svg = renderToStaticMarkup(createElement(lu[name]));
  glyphs[name.slice(2)] = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
}

const marks = {};
const source = readFileSync(site + "src/app/site/icons.ts", "utf8");
for (const [, json] of source.matchAll(/addCollection\((\{.*\})\);?\s*$/gm)) {
  const set = JSON.parse(json);
  for (const [id, icon] of Object.entries(set.icons)) {
    marks[`${set.prefix}:${id}`] = {
      body: icon.body,
      w: icon.width ?? set.width ?? 16,
      h: icon.height ?? set.height ?? 16,
    };
  }
}

writeFileSync(
  new URL("../src/lib/icons.generated.ts", import.meta.url),
  `/* Generated by scripts/icons.mjs: do not edit by hand. */\n` +
    `export const GLYPHS: Record<string, string> = ${JSON.stringify(glyphs, null, 1)};\n\n` +
    `export const MARK_ICONS: Record<string, { body: string; w: number; h: number }> = ${JSON.stringify(marks)};\n`,
);
console.log(Object.keys(glyphs).length, "glyphs,", Object.keys(marks).length, "marks");
